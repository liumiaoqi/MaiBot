for _, row in unmapped.iterrows():
    name = row['name']
    for industry, kws in kw_rules.items():
        if any(k in name for k in kws):
            ind = pd.concat([ind, pd.DataFrame([{'code': row['code'], 'industry': industry}])], ignore_index=True)
            assigned += 1
            break

ind = ind.drop_duplicates(subset='code')
